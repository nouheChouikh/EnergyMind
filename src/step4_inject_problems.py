"""Step 4 - inject the problems and write the dataset STEG would receive.

Output: data/readings_2018.parquet   learning year: normal behaviour, no problem
        data/readings_2019.parquet   practice + final test, with problems
        data/transformer.parquet     reference meter at the transformer, with the grid problems
        data/answers.csv             one row per injected problem (the answer key)
        data/RECIPES.md              what each problem type changes, its sizes and counts
"""
import pandas as pd

import config as C
from common import load_source, save_parquet, to_long, write_csv, write_text
from events import answers_frame, plan_events
from street import make_noise, simulate, transformer_frame


def read_wiring():
    return pd.read_csv(C.DATA_DIR / "wiring.csv", dtype={"home_id": str, "phase": str, "zip_code": str,
                                                         "goiener_user": str}, keep_default_na=False)


def build_final():
    home_ids, idx, kwh, est = load_source()
    wiring = read_wiring()
    events, skipped = plan_events(kwh, est, wiring, idx)
    out = simulate(kwh, wiring, make_noise(*kwh.shape), events)
    readings = to_long(home_ids, idx, out["kwh"], out["v"], out["i"], est)
    is_2018 = (readings["timestamp"].dt.year == 2018).to_numpy()
    return dict(events=events, skipped=skipped, out=out,
                readings_2018=readings[is_2018].reset_index(drop=True),
                readings_2019=readings[~is_2018].reset_index(drop=True),
                transformer=transformer_frame(idx, out),
                answers=answers_frame(events, wiring, idx))


def recipes_markdown(answers):
    counts = answers.groupby(["type", "period"]).size().unstack(fill_value=0)
    lines = [
        "# Recipes of the injected problems",
        "",
        "Generated by `src/step4_inject_problems.py` from the numbers in `src/config.py`.",
        "Every injected problem is listed in `answers.csv` with its homes, start, end, size and a one-line recipe.",
        "",
        "## Rules for every problem",
        "",
        "- Problems are injected only in 2019: practice (January to June) and final test (July to December). 2018 stays clean.",
        "- Each problem fits inside one calendar month of its period.",
        "- No problem touches an hour that GoiEner marked as estimated.",
        f"- No two problems touch the same home, and at least {C.BUFFER_H} free hours separate them.",
        "- Two problems that change the street energy balance never overlap on the same phase.",
        "- Sizes climb a ladder: subtle, medium, obvious.",
        "- Held-out type: " + ", ".join(f"`{k}`" for k, s in C.PROBLEMS.items() if s.get("held_out"))
        + ". It appears only in the final test, and no rule, verdict or feature is written for it.",
        "- `holiday_absence` and `new_ac` are real changes, not faults: they test that the system does not raise false alarms.",
        "",
        "## Problem types",
        "",
        "| Type | Category | What happens | Subtle / medium / obvious | Duration | Practice | Final test | Expected verdict |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for kind, spec in C.PROBLEMS.items():
        hours = " / ".join(f"{h} h" for h in spec["hours"])
        if spec["ladder"] == "size":
            ladder = " / ".join(str(s) for s in spec["sizes"]) + f" ({spec['unit']})"
            duration = f"one of {hours}"
        elif spec["ladder"] == "variant":
            ladder = " / ".join(spec["variants"])
            duration = f"one of {hours}"
        else:
            ladder, duration = hours, "the size"
        n_p = int(counts.at[kind, "practice"]) if kind in counts.index and "practice" in counts else 0
        n_f = int(counts.at[kind, "final_test"]) if kind in counts.index and "final_test" in counts else 0
        lines.append(f"| `{kind}` | {spec['category']} | {spec['what']} | {ladder} | {duration} | {n_p} | {n_f} | `{spec['verdict']}` |")
    lines += ["", f"Total: {len(answers)} problems ({int((answers['period'] == 'practice').sum())} practice, "
              f"{int((answers['period'] == 'final_test').sum())} final test).", ""]
    return "\n".join(lines)


def main():
    res = build_final()
    save_parquet(res["readings_2018"], C.DATA_DIR / "readings_2018.parquet")
    save_parquet(res["readings_2019"], C.DATA_DIR / "readings_2019.parquet")
    save_parquet(res["transformer"], C.DATA_DIR / "transformer.parquet")
    write_csv(res["answers"], C.DATA_DIR / "answers.csv")
    write_text(C.DATA_DIR / "RECIPES.md", recipes_markdown(res["answers"]))
    a = res["answers"]
    print(f"  {len(a)} problems injected: {int((a['period'] == 'practice').sum())} practice, "
          f"{int((a['period'] == 'final_test').sum())} final test")
    if res["skipped"]:
        print(f"  WARNING: could not place {len(res['skipped'])}: {', '.join(res['skipped'])}")


if __name__ == "__main__":
    main()
